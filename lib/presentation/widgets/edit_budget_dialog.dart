import 'package:flutter/material.dart';
import 'package:budgett_frontend/core/app_theme.dart';
import 'package:budgett_frontend/core/utils/error_messages.dart';
import 'package:budgett_frontend/presentation/utils/currency_formatter.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:budgett_frontend/presentation/providers/finance_provider.dart';
import 'package:budgett_frontend/data/models/budget_model.dart';
import 'package:budgett_frontend/data/models/sub_category_model.dart';
import 'package:budgett_frontend/presentation/utils/icon_helper.dart';
import '../../core/app_text.dart';

class EditBudgetDialog extends ConsumerStatefulWidget {
  final String categoryId;
  final String categoryName;
  final int month;
  final int year;
  /// Explicit category-level budget (a `budgets` row), or null when the
  /// category's budget comes only from its sub-categories.
  final double? currentAmount;

  /// Sub-categories that can get their own budget. When non-empty the
  /// category budget is optional and defaults to their sum.
  final List<SubCategory> subCategories;

  /// Current sub-category budgets, keyed by sub-category id.
  final Map<String, double> currentSubBudgets;
  final String? categoryType;
  final String? categoryIcon;
  final String? categoryColor;

  const EditBudgetDialog({
    super.key,
    required this.categoryId,
    required this.categoryName,
    required this.month,
    required this.year,
    this.currentAmount,
    this.subCategories = const [],
    this.currentSubBudgets = const {},
    this.categoryType,
    this.categoryIcon,
    this.categoryColor,
  });

  @override
  ConsumerState<EditBudgetDialog> createState() => _EditBudgetDialogState();
}

class _EditBudgetDialogState extends ConsumerState<EditBudgetDialog> {
  final _formKey = GlobalKey<FormState>();
  late final TextEditingController _amountController;
  late final Map<String, TextEditingController> _subControllers;

  /// Guards against double submission (double-tap / slow network), which would
  /// post the budget twice and pop the screen behind the dialog.
  bool _isLoading = false;

  bool get _hasSubs => widget.subCategories.isNotEmpty;

  static String _initialText(double? amount) => amount != null && amount > 0
      ? CurrencyFormatter.format(amount, includeSymbol: false)
      : '';

  @override
  void initState() {
    super.initState();
    _amountController = TextEditingController(
      text: widget.currentAmount != null
          ? CurrencyFormatter.format(widget.currentAmount!, includeSymbol: false)
          : '',
    )..addListener(_refresh);
    _subControllers = {
      for (final sub in widget.subCategories)
        sub.id: TextEditingController(
          text: _initialText(widget.currentSubBudgets[sub.id]),
        )..addListener(_refresh),
    };
  }

  void _refresh() {
    if (mounted) setState(() {});
  }

  @override
  void dispose() {
    _amountController.dispose();
    for (final c in _subControllers.values) {
      c.dispose();
    }
    super.dispose();
  }

  static double? _parseOptional(String text) {
    if (text.trim().isEmpty) return null;
    return CurrencyFormatter.parse(text);
  }

  Map<String, double?> get _subAmounts => {
        for (final e in _subControllers.entries)
          e.key: _parseOptional(e.value.text),
      };

  double get _subTotal =>
      _subAmounts.values.fold<double>(0.0, (sum, v) => sum + (v ?? 0.0));

  double? get _categoryAmount => _parseOptional(_amountController.text);

  Future<void> _saveBudget() async {
    if (_isLoading) return;
    if (!_formKey.currentState!.validate()) return;

    final repo = ref.read(financeRepositoryProvider);
    final categoryAmount = _categoryAmount;

    setState(() => _isLoading = true);
    try {
      if (_hasSubs) {
        await repo.setSubCategoryBudgets(
            widget.categoryId, widget.month, widget.year, _subAmounts);
      }

      if (categoryAmount == null) {
        // Empty category field -> the budget is the sum of sub-categories.
        if (widget.currentAmount != null) {
          await repo.deleteBudget(widget.categoryId, widget.month, widget.year);
        }
      } else {
        await repo.setBudget(Budget(
          id: '', // Will be generated by DB
          categoryId: widget.categoryId,
          amount: categoryAmount,
          month: widget.month,
          year: widget.year,
        ));
      }

      // Invalidate to refresh
      ref.invalidate(budgetsProvider);

      if (mounted) {
        Navigator.of(context).pop();
        ScaffoldMessenger.of(context).showSnackBar(
          const SnackBar(content: Text('Budget updated successfully')),
        );
      }
    } catch (e) {
      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(content: Text(friendlyError(e))),
        );
      }
    } finally {
      if (mounted) setState(() => _isLoading = false);
    }
  }

  Widget _buildSubCategoryFields(BuildContext context) {
    final muted = Theme.of(context).colorScheme.onSurfaceVariant;
    return Column(
      crossAxisAlignment: CrossAxisAlignment.stretch,
      mainAxisSize: MainAxisSize.min,
      children: [
        Text(
          'Subcategories',
          style:
              TextStyle(fontSize: 12, fontWeight: FontWeight.w600, color: muted),
        ),
        const SizedBox(height: 8),
        for (final (i, sub) in widget.subCategories.indexed)
          Padding(
            padding: const EdgeInsets.only(bottom: 8),
            child: Row(
              children: [
                Expanded(
                  flex: 5,
                  child: Text(
                    sub.name,
                    maxLines: 2,
                    overflow: TextOverflow.ellipsis,
                  ),
                ),
                const SizedBox(width: 8),
                Expanded(
                  flex: 6,
                  child: TextFormField(
                    key: ValueKey('sub-budget-${sub.id}'),
                    controller: _subControllers[sub.id],
                    autofocus: i == 0,
                    decoration: const InputDecoration(
                      prefixText: '\$',
                      hintText: '0',
                      isDense: true,
                      border: OutlineInputBorder(),
                    ),
                    keyboardType:
                        const TextInputType.numberWithOptions(decimal: true),
                    inputFormatters: [CurrencyInputFormatter()],
                    textAlign: TextAlign.end,
                    style: AppText.tabular(15, weight: 600),
                  ),
                ),
              ],
            ),
          ),
      ],
    );
  }

  Widget _buildSummary(BuildContext context, bool isIncome) {
    final scheme = Theme.of(context).colorScheme;
    final subTotal = _subTotal;
    final effective = Budget.effectiveAmount(_categoryAmount, {
      for (final e in _subAmounts.entries)
        if (e.value != null) e.key: e.value!,
    });
    final unassigned = (effective - subTotal).clamp(0.0, double.infinity);

    Widget line(String label, double value, {bool bold = false}) => Row(
          children: [
            Expanded(
              child: Text(
                label,
                style: TextStyle(
                  fontSize: 12,
                  fontWeight: bold ? FontWeight.w700 : null,
                  color: bold ? scheme.onSurface : scheme.onSurfaceVariant,
                ),
              ),
            ),
            Text(
              CurrencyFormatter.format(value),
              style: AppText.tabular(bold ? 15 : 12, weight: bold ? 700 : 500),
            ),
          ],
        );

    return Container(
      padding: const EdgeInsets.all(10),
      decoration: BoxDecoration(
        color: scheme.surfaceContainerHighest.withValues(alpha: 0.5),
        borderRadius: BorderRadius.circular(8),
      ),
      child: Column(
        mainAxisSize: MainAxisSize.min,
        children: [
          line('Subcategories', subTotal),
          if (unassigned > 0) ...[
            const SizedBox(height: 2),
            line('Unassigned', unassigned),
          ],
          const SizedBox(height: 4),
          line(isIncome ? 'Total expected' : 'Total budget', effective,
              bold: true),
        ],
      ),
    );
  }

  @override
  Widget build(BuildContext context) {
    final isIncome = widget.categoryType == 'income';
    final color = widget.categoryColor != null 
        ? Color(int.parse(widget.categoryColor!))
        : context.muted;
    
    return AlertDialog(
      title: Row(
        children: [
          if (widget.categoryIcon != null)
            Container(
              padding: const EdgeInsets.all(8),
              decoration: BoxDecoration(
                color: color.withValues(alpha: 0.2),
                borderRadius: BorderRadius.circular(8),
              ),
              child: Icon(
                IconHelper.getIcon(widget.categoryIcon!),
                color: color,
                size: 24,
              ),
            ),
          const SizedBox(width: 12),
          Expanded(
            child: Column(
              crossAxisAlignment: CrossAxisAlignment.start,
              mainAxisSize: MainAxisSize.min,
              children: [
                Text(
                  widget.categoryName,
                  style: Theme.of(context).textTheme.titleLarge,
                ),
                const SizedBox(height: 4),
                Container(
                  padding: const EdgeInsets.symmetric(horizontal: 8, vertical: 2),
                  decoration: BoxDecoration(
                    color: (isIncome
                            ? context.semantic.positive
                            : context.semantic.warning)
                        .withValues(alpha: 0.2),
                    borderRadius: BorderRadius.circular(12),
                  ),
                  child: Text(
                    isIncome ? 'Income' : 'Expense',
                    style: TextStyle(
                      fontSize: 12,
                      color: isIncome
                          ? context.semantic.positive
                          : context.semantic.warning,
                      fontWeight: FontWeight.bold,
                    ),
                  ),
                ),
              ],
            ),
          ),
        ],
      ),
      content: SizedBox(
        width: 420,
        child: Form(
          key: _formKey,
          child: SingleChildScrollView(
            child: Column(
              mainAxisSize: MainAxisSize.min,
              crossAxisAlignment: CrossAxisAlignment.stretch,
              children: [
                if (_hasSubs) ...[
                  _buildSubCategoryFields(context),
                  const SizedBox(height: 8),
                ],
                TextFormField(
                  key: const ValueKey('category-budget'),
                  controller: _amountController,
                  decoration: InputDecoration(
                    labelText: _hasSubs
                        ? (isIncome
                            ? 'Category expected income (optional)'
                            : 'Category budget (optional)')
                        : (isIncome ? 'Expected Income' : 'Budget Amount'),
                    helperText: _hasSubs
                        ? 'Leave empty to use the subcategory total. A higher amount overrides it.'
                        : null,
                    helperMaxLines: 3,
                    hintText: _hasSubs
                        ? CurrencyFormatter.format(_subTotal,
                            includeSymbol: false)
                        : null,
                    prefixText: '\$',
                    border: const OutlineInputBorder(),
                  ),
                  keyboardType:
                      const TextInputType.numberWithOptions(decimal: true),
                  inputFormatters: [CurrencyInputFormatter()],
                  style: AppText.tabular(22, weight: 700),
                  autofocus: !_hasSubs,
                  validator: (value) {
                    if (value == null || value.isEmpty) {
                      return _hasSubs ? null : 'Required';
                    }
                    final parsed = CurrencyFormatter.parse(value);
                    if (parsed == 0.0 && value != '0' && value != '0.0') {
                      return 'Invalid number';
                    }
                    if (_hasSubs && parsed < _subTotal) {
                      return 'Must be at least ${CurrencyFormatter.format(_subTotal)} (subcategory total)';
                    }
                    return null;
                  },
                ),
                if (_hasSubs) ...[
                  const SizedBox(height: 12),
                  _buildSummary(context, isIncome),
                ],
              ],
            ),
          ),
        ),
      ),
      actions: [
        TextButton(
          onPressed: () => Navigator.of(context).pop(),
          child: const Text('Cancel'),
        ),
        FilledButton(
          onPressed: _isLoading ? null : _saveBudget,
          child: _isLoading
              ? const SizedBox(
                  height: 20,
                  width: 20,
                  child: CircularProgressIndicator(strokeWidth: 2),
                )
              : const Text('Save'),
        ),
      ],
    );
  }
}
